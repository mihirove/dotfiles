#!/usr/bin/env python3
"""Turn mined review threads (JSONL from mine_review_examples.py) into references/examples/<repo>.md.

Each thread becomes one example: a trimmed diff hunk, the reviewer's comment, how the author
responded, and a category guess. Categories follow the 13 buckets in references/review-taxonomy.md.
The keyword classifier is deliberately simple; the skill reads the examples as a human would and
does not depend on the labels being perfect. Comments carrying an AI-assistant footer are tagged so
hand-written ones can be weighted for tone.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict

CATEGORIES = [
    ("1", "命名・可読性・コード品質", r"命名|名前|名称|rename|リネーム|readab|可読|重複|duplicate|DRY|typo|誤字|語彙|用語|統一|wording|表記|冗長|簡潔|分割|責務"),
    ("2", "アーキテクチャと設計", r"設計|アーキテクチャ|責務|依存|layer|レイヤ|境界|配置|モジュール|共通化|抽象|packages/|core|procedure|barrel"),
    ("3", "UI/UX とデザイン実装", r"UI|UX|画面|表示|ボタン|デザイン|token|トークン|css|スタイル|aria|a11y|アクセシビ|キーボード|文言|placeholder|レイアウト|VRT|スクショ|スクリーンショット|句点"),
    ("4", "CI/CD・ビルド・依存関係・環境", r"CI|workflow|ワークフロー|GitHub Actions|job|docker|compose|pnpm|依存関係|dependenc|lock|ビルド|build|timeout-minutes|runner|cache|デプロイ|deploy|atlantis|terraform|plan|apply"),
    ("5", "ドメインロジック・データ整合性・DB", r"DB|データ|テーブル|カラム|列|migration|マイグレーション|SQL|TypeORM|drizzle|index|インデック|Elasticsearch|ES |クエリ|query|整合|一意|unique|外部キー|FK|RLS|tenant|enum|ENUM|正規化|ソート|順序|ページ"),
    ("6", "エラーハンドリング・バリデーション・堅牢性", r"エラー|error|例外|exception|catch|throw|握り|ログ|log|validation|バリデーション|検証|retry|リトライ|timeout|タイムアウト|fail-?open|fail-?close|fallback|フォールバック|429|5\d\d|4\d\d|status"),
    ("7", "テストとカバレッジ", r"テスト|test|spec|E2E|e2e|vitest|playwright|jest|pytest|assert|expect|モック|mock|fixture|フィクスチャ|カバ|coverage|flaky|fixme|証跡|evidence|AC-|QA"),
    ("8", "型定義・スキーマ設計", r"型|type|interface|zod|schema|スキーマ|openapi|OpenAPI|any\b|unknown|null|undefined|optional|必須|nullable|as \w|アサーション|generics|infer"),
    ("9", "セキュリティと認証・認可", r"認証|認可|auth|権限|role|ロール|RBAC|IAP|token|トークン|secret|シークレット|PII|個人情報|漏|CSRF|XSS|injection|IDOR|所有|owner|session|cookie|Cookie|JWT|OIDC|PKCE|IAM|roles/"),
    ("10", "パフォーマンスと最適化", r"パフォーマンス|performance|N\+1|遅|速|重い|メモリ|memory|再描画|re-?render|useMemo|useCallback|並列|concurren|バッチ|batch|キャッシュ|cache|コスト|cost"),
    ("11", "ドキュメント・レビュープロセス・コミュニケーション", r"ドキュメント|docs?/|README|AGENTS\.md|CLAUDE\.md|コメント|comment|説明|PR 本文|PR本文|description|Why|なぜ|理由|背景|ADR|設計書|仕様書|issue|チケット|Linear|SV-|SKZ-|LAB-"),
    ("12", "状態管理と非同期処理", r"state|状態|useEffect|useState|zustand|Zustand|context|Context|async|await|Promise|非同期|競合|race|stale|closure|SSE|stream|ストリーム|購読|subscribe"),
    ("13", "タイムゾーン・日付・国際化", r"日付|日時|date|Date|time|時刻|タイムゾーン|timezone|JST|UTC|dayjs|i18n|翻訳|translation|locale|ロケール|月|境界日"),
]
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
AI_FOOTER_RE = re.compile(r"Generated by \[Claude Code\]|【AI(から)?の提案|Devin|Codex|Greptile|CodeRabbit|Copilot", re.I)


def classify(text: str) -> tuple[str, str]:
    scores = []
    for cid, name, pat in CATEGORIES:
        n = len(re.findall(pat, text))
        scores.append((n, cid, name))
    scores.sort(reverse=True)
    if scores[0][0] == 0:
        return "1", "命名・可読性・コード品質"
    return scores[0][1], scores[0][2]


def trim_hunk(h: str, max_lines: int = 10) -> str:
    lines = [l for l in h.splitlines() if not l.startswith("@@")]
    if len(lines) > max_lines:
        lines = lines[-max_lines:]
    return "\n".join(lines)


def author_outcome(replies: list[dict]) -> str:
    if not replies:
        return "返信なし"
    texts = " ".join(r["body"] for r in replies if r["by_author"])
    if re.search(r"修正|対応|直し|反映|削除|追加しました|移しました|変更しました|しました", texts):
        return "著者が対応"
    if re.search(r"意図|仕様|想定|そのまま|見送|別 ?PR|後続|issue|チケット", texts):
        return "著者が説明（現状維持 / 別途対応）"
    return "議論あり"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("jsonl")
    ap.add_argument("--out", required=True)
    ap.add_argument("--max-per-category", type=int, default=4)
    ap.add_argument("--max-comment-chars", type=int, default=550)
    ap.add_argument("--exclude-pr", type=int, action="append", default=[], help="leave these PRs out (e.g. held-out eval targets)")
    args = ap.parse_args()

    items = [json.loads(l) for l in open(args.jsonl, encoding="utf-8") if l.strip()]
    items = [i for i in items if i["pr"] not in set(args.exclude_pr)]
    inline = [i for i in items if i["kind"] == "inline" and i.get("diff_hunk")]
    summaries = [i for i in items if i["kind"] in ("review_summary", "conversation")]
    repo = items[0]["repo"] if items else "?"

    buckets: dict[str, list[dict]] = defaultdict(list)
    for it in inline:
        cid, name = classify(it["comment"] + " " + (it.get("path") or ""))
        it["_cat"] = (cid, name)
        it["_ai"] = bool(AI_FOOTER_RE.search(it["comment"]))
        buckets[cid].append(it)

    # Prefer hand-written, author-acknowledged, recent threads; cap per category.
    def rank(it):
        # Newest first within the same tier: the team's conventions drift, recent threads reflect them.
        return (0 if not it["_ai"] else 1, 0 if any(r["by_author"] for r in it["replies"]) else 1, "" if not it["merged_at"] else "".join(chr(0x10FFFF - ord(ch)) for ch in it["merged_at"]))
    out = []
    out.append(f"# Review examples mined from {repo}\n")
    out.append(f"Source: {len(inline)} inline review threads and {len(summaries)} PR-level comments from "
               f"{len({i['pr'] for i in items})} merged PRs (humans only; author, bots and bare approvals removed). "
               f"Each example is: the hunk the reviewer pointed at → what they said → what the author did. "
               f"`AI-assisted` marks comments posted with an AI assistant footer; they count for substance, "
               f"hand-written ones also for tone.\n")
    counts = {cid: len(v) for cid, v in buckets.items()}
    out.append("| # | category | threads |\n|---|---|---|")
    for cid, name, _ in CATEGORIES:
        out.append(f"| {cid} | {name} | {counts.get(cid, 0)} |")
    out.append("")

    for cid, name, _ in CATEGORIES:
        its = sorted(buckets.get(cid, []), key=rank)[: args.max_per_category]
        if not its:
            continue
        out.append(f"## {cid}. {name}\n")
        for it in its:
            tag = " · AI-assisted" if it["_ai"] else ""
            out.append(f"### PR #{it['pr']} · `{it['path']}`{tag}\n")
            out.append("```diff\n" + trim_hunk(it["diff_hunk"]) + "\n```")
            c = re.sub(r"\n---\n_Generated by.*$", "", it["comment"], flags=re.S).strip()
            if len(c) > args.max_comment_chars:
                c = c[: args.max_comment_chars].rstrip() + " …"
            out.append("**Reviewer:**\n> " + c.replace("\n", "\n> "))
            auth = [r for r in it["replies"] if r["by_author"]]
            if auth:
                a = auth[-1]["body"].strip()
                a = re.sub(r"\n---\n_Generated by.*$", "", a, flags=re.S).strip()
                if len(a) > 300:
                    a = a[:300].rstrip() + " …"
                out.append(f"**Author ({author_outcome(it['replies'])}):**\n> " + a.replace("\n", "\n> "))
            else:
                out.append(f"**Outcome:** {author_outcome(it['replies'])}")
            out.append("")

    good_summaries = [s for s in summaries if len(s["comment"]) > 60][:8]
    if good_summaries:
        out.append("## PR-level review summaries (how approvals and pushbacks are worded)\n")
        for s in good_summaries:
            c = re.sub(r"\n---\n_Generated by.*$", "", s["comment"], flags=re.S).strip()
            if len(c) > 600:
                c = c[:600].rstrip() + " …"
            state = f" · {s.get('review_state')}" if s.get("review_state") else ""
            out.append(f"### PR #{s['pr']}{state}\n> " + c.replace("\n", "\n> ") + "\n")

    text = EMAIL_RE.sub("<email>", "\n".join(out))
    open(args.out, "w", encoding="utf-8").write(text)
    print(f"wrote {args.out}: {sum(min(len(v), args.max_per_category) for v in buckets.values())} examples", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
